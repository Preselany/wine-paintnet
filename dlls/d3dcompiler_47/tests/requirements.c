START_TEST(requirements)
{
    ID3D11ShaderReflection *reflection;
    D3D11_SHADER_DESC desc;
    D3D_FEATURE_LEVEL level;
    UINT64 requires;
    unsigned int i;
    HRESULT hr;
    for (i = 0; i < ARRAY_SIZE(cases); ++i)
    {
        winetest_push_context("%s",cases[i].name);
        hr = D3DReflect(cases[i].data,cases[i].size,&IID_ID3D11ShaderReflection,(void **)&reflection);
        ok(hr == S_OK,"Reflect returned %#lx.\n",hr);
        if (SUCCEEDED(hr))
        {
            hr = reflection->lpVtbl->GetDesc(reflection,&desc);
            ok(hr == S_OK && desc.Version == cases[i].version,"Version %#x, hr %#lx.\n",desc.Version,hr);
            level = 0;
            hr = reflection->lpVtbl->GetMinFeatureLevel(reflection,&level);
            ok(hr == S_OK && level == cases[i].level,"Minimum level %#x, expected %#x, hr %#lx.\n",level,cases[i].level,hr);
            requires = reflection->lpVtbl->GetRequiresFlags(reflection);
            ok(requires == cases[i].requires,"Required flags %#I64x, expected %#I64x.\n",requires,cases[i].requires);
            reflection->lpVtbl->Release(reflection);
        }
        winetest_pop_context();
    }
}
