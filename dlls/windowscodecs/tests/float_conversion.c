static void test_unpremultiply(IWICImagingFactory *factory)
{
    static const GUID *sources[] = {&GUID_WICPixelFormat32bppPBGRA, &GUID_WICPixelFormat32bppPRGBA};
    IWICFormatConverter *converter;
    IWICBitmap *bitmap;
    BYTE *input = malloc(256 * 256 * 4);
    float *output = malloc(256 * 256 * 16), gamma[256], best, error;
    unsigned int src, x, y, k, index;
    DWORD hash;
    HRESULT hr;

    ok(input && output, "Failed to allocate unpremultiplication image.\n");
    if (!input || !output) goto done;
    for (k = 0; k < 256; ++k)
    {
        double value = k / 255.0;
        gamma[k] = value <= .04045 ? value / 12.92 : pow((value + .055) / 1.055, 2.4);
    }
    for (y = 0; y < 256; ++y)
        for (x = 0; x < 256; ++x)
        {
            input[(y * 256 + x) * 4] = input[(y * 256 + x) * 4 + 1] = input[(y * 256 + x) * 4 + 2] = x;
            input[(y * 256 + x) * 4 + 3] = y;
        }
    for (src = 0; src < 2; ++src)
    {
        REQUIRE(IWICImagingFactory_CreateBitmapFromMemory(factory, 256, 256, sources[src], 1024,
                256 * 256 * 4, input, &bitmap));
        REQUIRE(IWICImagingFactory_CreateFormatConverter(factory, &converter));
        REQUIRE(IWICFormatConverter_Initialize(converter, (IWICBitmapSource *)bitmap,
                &GUID_WICPixelFormat128bppRGBAFloat, WICBitmapDitherTypeNone, NULL, 0, WICBitmapPaletteTypeCustom));
        hr = IWICFormatConverter_CopyPixels(converter, NULL, 4096, 256 * 256 * 16, (BYTE *)output);
        ok(hr == S_OK, "Source %u copy %#lx.\n", src, hr);
        if (SUCCEEDED(hr))
            for (y = 0; y < 256; ++y)
            {
                hash = 2166136261u;
                for (x = 0; x < 256; ++x)
                {
                    float *pixel = output + (y * 256 + x) * 4;
                    best = 1e9f;
                    index = 999;
                    for (k = 0; k < 256; ++k)
                    {
                        error = fabsf(gamma[k] - pixel[0]);
                        if (error < best) {best = error; index = k;}
                    }
                    ok(best <= 2e-7f && pixel[1] == pixel[0] && pixel[2] == pixel[0] && pixel[3] == y / 255.0f,
                            "Source %u channel %u alpha %u: invalid color/alpha.\n", src, x, y);
                    hash = (hash ^ index) * 16777619u;
                }
                ok(hash == unpremultiply_hashes[src][y], "Source %u alpha %u: channel hash %#lx, expected %#lx.\n",
                        src, y, hash, unpremultiply_hashes[src][y]);
            }
        IWICFormatConverter_Release(converter);
        IWICBitmap_Release(bitmap);
    }
done:
    free(input);
    free(output);
}

